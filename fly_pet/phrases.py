"""Русские фразы реплик питомца (по 2–3 варианта на событие)."""

from __future__ import annotations

import random

PHRASES: dict[str, list[str]] = {
    "greeting": [
        "Привет! Я тут.",
        "Жужжу на месте.",
        "Снова на столе.",
    ],
    "hungry": [
        "Есть охота…",
        "Голодно как-то.",
        "Неплохо бы перекусить.",
    ],
    "sleepy": [
        "Глаза слипаются.",
        "Посплю немного.",
        "Сил почти нет.",
    ],
    "bored": [
        "Скучновато…",
        "Эй, я ещё здесь.",
        "Развей меня чем-нибудь.",
    ],
    "woke": [
        "Проснулась.",
        "Уже лучше.",
        "Хватит дремать.",
    ],
}


def pick(event: str) -> str:
    """Возвращает случайную фразу для события; неизвестный ключ — пустая строка."""
    variants = PHRASES.get(event) or []
    if not variants:
        return ""
    return random.choice(variants)
